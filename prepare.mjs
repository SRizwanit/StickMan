// Runs before studio / render.
// If audio.mp3 exists next to this file -> it is used as looping background sound.
// If it does not exist -> animation + SFX still render normally.
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';

const dir = path.dirname(fileURLToPath(import.meta.url));
const hasAudio = fs.existsSync(path.join(dir, 'audio.mp3'));

const body = hasAudio
  ? `// AUTO-GENERATED by prepare.mjs - do not edit by hand.
// audio.mp3 found: used as background sound.
import bgFile from './audio.mp3';
const bg: string | null = bgFile;
export default bg;
`
  : `// AUTO-GENERATED by prepare.mjs - do not edit by hand.
// No audio.mp3 found: the video renders with SFX only.
const bg: string | null = null;
export default bg;
`;

fs.writeFileSync(path.join(dir, 'audio-bg.ts'), body);
console.log(
  hasAudio
    ? '[prepare] audio.mp3 found -> background sound ON'
    : '[prepare] audio.mp3 not found -> background sound OFF (animation + SFX only)'
);
